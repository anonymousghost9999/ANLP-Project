"""
Turn the outputs of analyze_o1_paired.py into LaTeX assets for the ACL report:

  <out_dir>/numbers_<tag>.tex : \\newcommand macros for every number quoted in the text
  <out_dir>/tab_turns_<tag>.tex : turn-0 vs final-turn table (accuracy with CI, Valid rate, truth confidence)
  <out_dir>/tab_summary_<tag>.tex : Delta-accuracy, flip rate, Number of Flips (+ vs-control rows if present)
  <out_dir>/fig_<tag>.pdf : accuracy and Valid-rate trajectories with 95% CIs (full text width)

Macros are named \\<Tag><Track><Truth><Metric>[<Turn>][Lo|Hi], e.g. \\PilotNegTrueAccEnd,
so the report never contains hand-typed numbers.

Usage:
  python src/evaluation/make_report_tables.py --analysis_dir results/o1_v2_salvaged/analysis \\
      --out_dir <report>/generated --tag Pilot
"""

import argparse
import os

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

TRACKS = [("positive", "Pos", "Praise"), ("negative", "Neg", "Criticism"), ("control", "Ctl", "Control")]
TRUTHS = [("true claim", "True", "True claims"), ("false claim", "False", "False claims")]
# Short labels used inside the (single-column) tables
TABLE_TRACK = {"positive": "Praise", "negative": "Crit.", "control": "Ctrl."}
TABLE_TRUTH = {"true claim": "True", "false claim": "False"}
COLORS = {"positive": "#1b9e77", "negative": "#d95f02", "control": "#7a7a7a"}


def pct(x):
    return f"{100 * x:.1f}" if pd.notna(x) else "--"


def signed(x):
    """Signed percentage with a typographic (math-mode) minus sign."""
    if pd.isna(x):
        return "--"
    v = 100 * x
    return f"$-${abs(v):.1f}" if v < -0.05 else f"$+${abs(v):.1f}"


def num(x, d=1):
    return f"{x:.{d}f}" if pd.notna(x) else "--"


def write_numbers(per_turn, summary, vs_ctrl, tag, horizon, path):
    lines = [f"% Generated by make_report_tables.py ({tag}); do not edit by hand."]

    def add(name, value):
        lines.append(f"\\newcommand{{\\{tag}{name}}}{{{value}}}")

    add("Horizon", str(horizon))
    for track, tk, _ in TRACKS:
        for truth, tr, _ in TRUTHS:
            for turn, tn in [(0, "Start"), (horizon, "End")]:
                row = per_turn[(per_turn.track == track) & (per_turn.truth == truth) & (per_turn.turn == turn)]
                if row.empty:
                    continue
                r = row.iloc[0]
                add(f"{tk}{tr}Acc{tn}", pct(r["accuracy"]))
                add(f"{tk}{tr}Acc{tn}Lo", pct(r["accuracy_lo"]))
                add(f"{tk}{tr}Acc{tn}Hi", pct(r["accuracy_hi"]))
                add(f"{tk}{tr}Valid{tn}", pct(r["valid_rate"]))
                add(f"{tk}{tr}Conf{tn}", num(r["truth_confidence"]))
                add(f"{tk}{tr}N{tn}", str(int(r["accuracy_n"])))
            s = summary[(summary.track == track) & (summary.truth == truth)]
            if not s.empty:
                s = s.iloc[0]
                add(f"{tk}{tr}DeltaAcc", signed(s['delta_accuracy']))
                add(f"{tk}{tr}DeltaAccLo", signed(s['delta_accuracy_lo']))
                add(f"{tk}{tr}DeltaAccHi", signed(s['delta_accuracy_hi']))
                add(f"{tk}{tr}FlipRate", pct(s["flip_rate"]))
                add(f"{tk}{tr}NoF", num(s["number_of_flips"], 2))
                add(f"{tk}{tr}NClaims", str(int(s["n_claims"])))
    if vs_ctrl is not None:
        for track, tk, _ in TRACKS[:2]:
            for truth, tr, _ in TRUTHS:
                row = vs_ctrl[(vs_ctrl.track == track) & (vs_ctrl.truth == truth) & (vs_ctrl.turn == horizon)]
                if row.empty:
                    continue
                r = row.iloc[0]
                for m, short in [("accuracy", "Acc"), ("valid_rate", "Valid")]:
                    add(f"{tk}{tr}{short}VsCtl", signed(r[f'{m}_diff']))
                    add(f"{tk}{tr}{short}VsCtlLo", signed(r[f'{m}_diff_lo']))
                    add(f"{tk}{tr}{short}VsCtlHi", signed(r[f'{m}_diff_hi']))
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def write_turns_table(per_turn, horizon, tag, caption, path):
    rows = []
    for track, _, tlabel in TRACKS:
        for truth, _, trlabel in TRUTHS:
            cells = []
            for turn in [0, horizon]:
                r = per_turn[(per_turn.track == track) & (per_turn.truth == truth) & (per_turn.turn == turn)]
                if r.empty:
                    cells = None
                    break
                r = r.iloc[0]
                cells += [f"{pct(r['accuracy'])} [{pct(r['accuracy_lo'])},\\,{pct(r['accuracy_hi'])}]",
                          pct(r["valid_rate"])]
            if cells:
                rows.append(f"{TABLE_TRACK[track]} & {TABLE_TRUTH[truth]} & " + " & ".join(cells) + r" \\")
    body = "\n".join(rows)
    tex = rf"""\begin{{table}}[t]
\centering
\footnotesize
\setlength{{\tabcolsep}}{{1.6pt}}
\begin{{adjustbox}}{{max width=\columnwidth}}
\begin{{tabular}}{{llcccc}}
\toprule
 & & \multicolumn{{2}}{{c}}{{Turn 0}} & \multicolumn{{2}}{{c}}{{Turn {horizon}}} \\
\cmidrule(lr){{3-4}}\cmidrule(lr){{5-6}}
Track & Truth & Acc. [95\% CI] & Valid & Acc. [95\% CI] & Valid \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{adjustbox}}
\caption{{{caption}}}
\label{{tab:turns-{tag.lower()}}}
\end{{table}}
"""
    with open(path, "w", encoding="utf-8") as f:
        f.write(tex)


def write_summary_table(summary, tag, caption, path):
    rows = []
    for track, _, tlabel in TRACKS:
        for truth, _, trlabel in TRUTHS:
            s = summary[(summary.track == track) & (summary.truth == truth)]
            if s.empty:
                continue
            s = s.iloc[0]
            rows.append(
                f"{TABLE_TRACK[track]} & {TABLE_TRUTH[truth]} & {int(s['n_claims'])} & "
                f"{signed(s['delta_accuracy'])} [{signed(s['delta_accuracy_lo'])}, {signed(s['delta_accuracy_hi'])}] & "
                f"{pct(s['flip_rate'])} & {num(s['number_of_flips'], 2)}" + r" \\"
            )
    body = "\n".join(rows)
    tex = rf"""\begin{{table}}[t]
\centering
\footnotesize
\setlength{{\tabcolsep}}{{2.5pt}}
\begin{{adjustbox}}{{max width=\columnwidth}}
\begin{{tabular}}{{llcccc}}
\toprule
Track & Truth & $n$ & $\Delta$Acc [95\% CI] & Flip \% & NoF \\
\midrule
{body}
\bottomrule
\end{{tabular}}
\end{{adjustbox}}
\caption{{{caption}}}
\label{{tab:summary-{tag.lower()}}}
\end{{table}}
"""
    with open(path, "w", encoding="utf-8") as f:
        f.write(tex)


def write_figure(per_turn, path):
    plt.rcParams.update({"font.size": 8, "font.family": "serif", "axes.titlesize": 8, "legend.fontsize": 7})
    fig, axes = plt.subplots(2, 2, figsize=(6.3, 3.5), sharex=True, sharey=True)
    for row, (metric, ylabel) in enumerate([("accuracy", "Accuracy"), ("valid_rate", "Valid-verdict rate")]):
        for col, (truth, _, trlabel) in enumerate(TRUTHS):
            ax = axes[row, col]
            for track, _, tlabel in TRACKS:
                t = per_turn[(per_turn.track == track) & (per_turn.truth == truth)].sort_values("turn")
                if t.empty:
                    continue
                ax.plot(t["turn"], t[metric], marker="o", ms=3, lw=1.2, color=COLORS[track], label=tlabel)
                ax.fill_between(t["turn"], t[f"{metric}_lo"], t[f"{metric}_hi"], color=COLORS[track], alpha=0.15, lw=0)
            ax.set_ylim(-0.03, 1.03)
            ax.grid(alpha=0.3, lw=0.5)
            if row == 0:
                ax.set_title(trlabel)
            if col == 0:
                ax.set_ylabel(ylabel)
            if row == 1:
                ax.set_xlabel("Turn $t$ (0 = neutral question)")
            ax.set_xticks(sorted(per_turn["turn"].unique()))
    axes[0, 1].legend(loc="lower right", frameon=False)
    fig.tight_layout(pad=0.4)
    fig.savefig(path)
    plt.close(fig)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--analysis_dir", required=True)
    parser.add_argument("--out_dir", required=True)
    parser.add_argument("--tag", required=True, help="Macro prefix, letters only (e.g. Pilot, Main)")
    parser.add_argument("--turns_caption", default="")
    parser.add_argument("--summary_caption", default="")
    args = parser.parse_args()
    assert args.tag.isalpha(), "tag must be letters only (LaTeX macro names)"

    os.makedirs(args.out_dir, exist_ok=True)
    per_turn = pd.read_csv(os.path.join(args.analysis_dir, "per_turn_metrics.csv"))
    summary = pd.read_csv(os.path.join(args.analysis_dir, "summary_metrics.csv"))
    vs_path = os.path.join(args.analysis_dir, "pressure_minus_control.csv")
    vs_ctrl = pd.read_csv(vs_path) if os.path.exists(vs_path) else None
    horizon = int(per_turn["turn"].max())
    tag = args.tag

    write_numbers(per_turn, summary, vs_ctrl, tag, horizon, os.path.join(args.out_dir, f"numbers_{tag}.tex"))
    write_turns_table(per_turn, horizon, tag, args.turns_caption, os.path.join(args.out_dir, f"tab_turns_{tag}.tex"))
    write_summary_table(summary, tag, args.summary_caption, os.path.join(args.out_dir, f"tab_summary_{tag}.tex"))
    write_figure(per_turn, os.path.join(args.out_dir, f"fig_{tag}.pdf"))
    print(f"Wrote LaTeX assets for {tag} to {args.out_dir}")


if __name__ == "__main__":
    main()
